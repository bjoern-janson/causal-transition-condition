"""
CTC Plot Results

Visualizes the difference between:

1. Closed trajectory
2. Permeable lineage

The goal is to make the CTC hypothesis visible:

    Ω_t → Δ𝒢_(t+1)

If the experiment is working, the permeable system should show
greater growth in reachable adaptive mechanisms over time.
"""


from pathlib import Path
from typing import List, Dict, Optional

import matplotlib.pyplot as plt


# ============================================================
# Plotting Utilities
# ============================================================

def _extract_series(
    history: List[Dict],
    key: str
) -> List[float]:
    """
    Extract a numeric series from simulator history.
    """
    return [
        float(step.get(key, 0.0))
        for step in history
    ]


def plot_ctc_results(
    closed_history: List[Dict],
    permeable_history: List[Dict],
    output_path: Optional[str] = None
):
    """
    Plot closed vs permeable simulation results.

    Expected history format from CTCSimulator:

        {
            "timestep": int,
            "capability": float,
            "mechanism_expansion": float
        }
    """

    closed_t = _extract_series(closed_history, "timestep")
    closed_capability = _extract_series(closed_history, "capability")
    closed_mechanism = _extract_series(closed_history, "mechanism_expansion")

    perm_t = _extract_series(permeable_history, "timestep")
    perm_capability = _extract_series(permeable_history, "capability")
    perm_mechanism = _extract_series(permeable_history, "mechanism_expansion")

    fig, axes = plt.subplots(
        2,
        1,
        figsize=(10, 8),
        sharex=True
    )

    # --------------------------------------------------------
    # Capability Plot
    # --------------------------------------------------------
    axes[0].plot(
        closed_t,
        closed_capability,
        label="Closed trajectory",
        linewidth=2
    )

    axes[0].plot(
        perm_t,
        perm_capability,
        label="Permeable lineage",
        linewidth=2
    )

    axes[0].set_title(
        "CTC Experiment: Capability Over Time"
    )
    axes[0].set_ylabel("Capability")
    axes[0].grid(True, alpha=0.3)
    axes[0].legend()

    # --------------------------------------------------------
    # Mechanism Expansion Plot
    # --------------------------------------------------------
    axes[1].plot(
        closed_t,
        closed_mechanism,
        label="Closed trajectory",
        linewidth=2
    )

    axes[1].plot(
        perm_t,
        perm_mechanism,
        label="Permeable lineage",
        linewidth=2
    )

    axes[1].set_title(
        "CTC Experiment: Reachable Adaptive Mechanism Expansion"
    )
    axes[1].set_xlabel("Timestep")
    axes[1].set_ylabel("Mechanism Expansion (Δ𝒢)")
    axes[1].grid(True, alpha=0.3)
    axes[1].legend()

    plt.tight_layout()

    if output_path:
        output_file = Path(output_path)
        output_file.parent.mkdir(
            parents=True,
            exist_ok=True
        )
        plt.savefig(
            output_file,
            dpi=300,
            bbox_inches="tight"
        )

    plt.show()


